#!/usr/bin/env node
/**
 * purge-opinions.mjs — OpinionBank hygiene script.
 *
 * Uses the PATCHED algorithm (extractWords + Math.min + polarity detection)
 * to audit existing opinions and clean up duplicates, test artifacts, and
 * contradictions that the old code missed.
 *
 * Usage:
 *   node scripts/purge-opinions.mjs                  # dry-run (report only)
 *   node scripts/purge-opinions.mjs --apply           # apply changes
 *   node scripts/purge-opinions.mjs --apply --backup   # backup + apply
 */

import { readFileSync, writeFileSync, copyFileSync, existsSync } from "fs";
import { join } from "path";

// ─── Config ────────────────────────────────────────────────────────────────
const MEMORY_PATH = join(process.cwd(), "docs", "memory");
const OPINIONS_FILE = join(MEMORY_PATH, "14_OPINIONS.md");
const SIMILARITY_THRESHOLD = 0.6;

const args = process.argv.slice(2);
const DRY_RUN = !args.includes("--apply");
const BACKUP = args.includes("--backup");

// ─── extractWords (same as patched opinion-bank.ts) ─────────────────────────
function extractWords(text) {
  return new Set(
    text
      .toLowerCase()
      .split(/\s+/)
      .map((w) => w.replace(/^[^\wáéíóúñü]+|[^\wáéíóúñü]+$/g, ""))
      .filter((w) => w.length > 3)
  );
}

// ─── Similarity (Math.min denominator, >= threshold) ────────────────────────
function similarity(a, b) {
  const wordsA = extractWords(a);
  const wordsB = extractWords(b);
  if (wordsA.size === 0 || wordsB.size === 0) return 0;
  let overlap = 0;
  for (const w of wordsA) {
    if (wordsB.has(w)) overlap++;
  }
  return overlap / Math.min(wordsA.size, wordsB.size);
}

// ─── Polarity (main clause only) ───────────────────────────────────────────
function isPolarityOpposite(a, b) {
  const mainClause = (s) => s.split(/\s*[—;.]\s*/)[0] || s;
  // Exempt scope qualifiers: "no solo", "not only", "not just" aren't stance negations
  const cleanForPolarity = (s) =>
    s.replace(/\bno solo\b/gi, "")
     .replace(/\bnot only\b/gi, "")
     .replace(/\bnot just\b/gi, "");
  const negPattern =
    /\b(nunca|never|no|don't|dont|avoid|not|jamás|jamas|prohibido|forbidden|evitar|stop|malo|bad|incorrecto|incorrect|wrong)\b/gi;

  const mainA = cleanForPolarity(mainClause(a));
  const mainB = cleanForPolarity(mainClause(b));

  const aHasNeg = negPattern.test(mainA);
  negPattern.lastIndex = 0;
  const bHasNeg = negPattern.test(mainB);

  return aHasNeg !== bHasNeg;
}

// ─── Parse opinions from 14_OPINIONS.md ─────────────────────────────────────
function parseOpinions(content) {
  const opinions = [];
  const lines = content.split("\n");
  let current = null;
  let currentDomain = "general";

  for (const line of lines) {
    const domainMatch = line.match(/^## (\w+)/);
    if (domainMatch) {
      currentDomain = domainMatch[1];
      continue;
    }
    const idMatch = line.match(/^### (op_\w+)/);
    if (idMatch) {
      if (current && current.id && current.statement) {
        current.domain = current.domain || currentDomain;
        opinions.push(current);
      }
      current = { id: idMatch[1], domain: currentDomain, evidence: { supporting: [], contradicting: [] } };
      continue;
    }
    if (!current) continue;

    const stmtMatch = line.match(/^- \*\*Statement\*\*: (.+)/);
    if (stmtMatch) { current.statement = stmtMatch[1]; continue; }
    const confMatch = line.match(/^- \*\*Confidence\*\*: ([\d.]+)/);
    if (confMatch) { current.confidence = parseFloat(confMatch[1]); continue; }
    const createdMatch = line.match(/^- \*\*Created\*\*: (.+)/);
    if (createdMatch) { current.createdAt = createdMatch[1]; continue; }
    const updatedMatch = line.match(/^- \*\*Updated\*\*: (.+)/);
    if (updatedMatch) { current.lastUpdated = updatedMatch[1]; continue; }
    const supMatch = line.match(/^- \*\*Supporting\*\*: (.+)/);
    if (supMatch) { current.evidence.supporting = supMatch[1].split("; ").filter(Boolean); continue; }
    const conMatch = line.match(/^- \*\*Contradicting\*\*: (.+)/);
    if (conMatch) { current.evidence.contradicting = conMatch[1].split("; ").filter(Boolean); continue; }
  }
  if (current && current.id && current.statement) {
    current.domain = current.domain || currentDomain;
    opinions.push(current);
  }
  return opinions;
}

// ─── Serialize opinions back to Markdown ────────────────────────────────────
function serialize(opinions) {
  const lines = [
    "# Opinion Bank",
    "",
    `> Auto-generated by Project Brain. ${opinions.length} opinions tracked.`,
    `> Last updated: ${new Date().toISOString().split("T")[0]}`,
    "",
  ];

  const grouped = new Map();
  for (const op of opinions) {
    const list = grouped.get(op.domain) || [];
    list.push(op);
    grouped.set(op.domain, list);
  }

  for (const [domain, ops] of grouped) {
    lines.push(`## ${domain}`);
    lines.push("");
    for (const op of ops.sort((a, b) => (b.confidence ?? 0.5) - (a.confidence ?? 0.5))) {
      lines.push(`### ${op.id}`);
      lines.push("");
      lines.push(`- **Statement**: ${op.statement}`);
      lines.push(`- **Confidence**: ${(op.confidence ?? 0.5).toFixed(2)}`);
      lines.push(`- **Created**: ${op.createdAt || "unknown"}`);
      lines.push(`- **Updated**: ${op.lastUpdated || "unknown"}`);
      if (op.evidence.supporting.length > 0) {
        lines.push(`- **Supporting**: ${op.evidence.supporting.join("; ")}`);
      }
      if (op.evidence.contradicting.length > 0) {
        lines.push(`- **Contradicting**: ${op.evidence.contradicting.join("; ")}`);
      }
      lines.push("");
    }
  }
  return lines.join("\n");
}

// ─── Test artifact detection ────────────────────────────────────────────────
const TEST_PATTERNS = [
  /\bFIRE TEST\b/i,
  /\btest pipeline\b/i,
  /\btest result\b/i,
  /\bsmoke test\b/i,
  /^(FIRE TEST|TEST)\s*\d/i,
];

function isTestArtifact(statement) {
  return TEST_PATTERNS.some((p) => p.test(statement));
}

// ─── Main ───────────────────────────────────────────────────────────────────
console.log("🏴‍☠️ OpinionBank Purge Script");
console.log(`   Mode: ${DRY_RUN ? "DRY RUN (add --apply to execute)" : "APPLYING CHANGES"}`);
console.log("");

if (!existsSync(OPINIONS_FILE)) {
  console.error(`❌ File not found: ${OPINIONS_FILE}`);
  process.exit(1);
}

const content = readFileSync(OPINIONS_FILE, "utf-8");
const opinions = parseOpinions(content);
console.log(`📋 Loaded ${opinions.length} opinions\n`);

const report = {
  duplicates: [],    // pairs to merge
  testArtifacts: [], // opinions to remove
  contradictions: [], // pairs with opposite polarity
  crossDomain: [],   // same opinion in different domains
};

// ─── 1. Detect duplicates & contradictions ──────────────────────────────────
console.log("═══ SIMILARITY ANALYSIS ═══\n");
for (let i = 0; i < opinions.length; i++) {
  for (let j = i + 1; j < opinions.length; j++) {
    const sim = similarity(opinions[i].statement, opinions[j].statement);
    if (sim >= SIMILARITY_THRESHOLD) {
      const isContra = isPolarityOpposite(opinions[i].statement, opinions[j].statement);
      const entry = {
        op1: opinions[i],
        op2: opinions[j],
        similarity: sim,
        isContradiction: isContra,
        crossDomain: opinions[i].domain !== opinions[j].domain,
      };

      if (isContra && !entry.crossDomain) {
        report.contradictions.push(entry);
      } else {
        // Cross-domain similar opinions are duplicates (classification error), not contradictions
        report.duplicates.push(entry);
      }

      if (entry.crossDomain) {
        report.crossDomain.push(entry);
      }

      const label = isContra ? "⚡ CONTRADICTION" : "🔄 DUPLICATE";
      const domainNote = entry.crossDomain ? ` [CROSS-DOMAIN: ${opinions[i].domain}↔${opinions[j].domain}]` : "";
      console.log(`${label} (${(sim * 100).toFixed(1)}%)${domainNote}`);
      console.log(`   ${opinions[i].id} (c=${(opinions[i].confidence ?? 0.5).toFixed(2)}): "${opinions[i].statement.substring(0, 70)}..."`);
      console.log(`   ${opinions[j].id} (c=${(opinions[j].confidence ?? 0.5).toFixed(2)}): "${opinions[j].statement.substring(0, 70)}..."`);
      console.log("");
    }
  }
}

// ─── 2. Detect test artifacts ───────────────────────────────────────────────
console.log("═══ TEST ARTIFACTS ═══\n");
for (const op of opinions) {
  if (isTestArtifact(op.statement)) {
    report.testArtifacts.push(op);
    console.log(`🧪 ${op.id} (c=${(op.confidence ?? 0.5).toFixed(2)}): "${op.statement.substring(0, 80)}..."`);
  }
}
if (report.testArtifacts.length === 0) console.log("   (none found)\n");
else console.log("");

// ─── 3. Detect low-value opinions (low confidence + generic) ────────────────
console.log("═══ LOW-VALUE (c < 0.3 + generic statement) ═══\n");
const lowValue = opinions.filter(
  (o) => (o.confidence ?? 0.5) < 0.3 && o.evidence.supporting.length <= 1
);
if (lowValue.length === 0) console.log("   (none found)\n");
for (const op of lowValue) {
  console.log(`📉 ${op.id} (c=${(op.confidence ?? 0.5).toFixed(2)}): "${op.statement.substring(0, 80)}"`);
}

// ─── Known duplicate pairs (detected manually, below algorithm threshold) ───
const KNOWN_DUPES = [
  // Both about deploy discipline: npm run deploy >> Copy-Item
  ["op_ofrw3o", "op_2wg0qg"],
  // Both about countLines bug: problem statement + fix
  ["op_xl3ztb", "op_xwc3hk"],
];

console.log("\n═══ KNOWN DUPLICATE PAIRS (manual) ═══\n");
for (const [id1, id2] of KNOWN_DUPES) {
  const o1 = opinions.find((o) => o.id === id1);
  const o2 = opinions.find((o) => o.id === id2);
  if (o1 && o2) {
    const sim = similarity(o1.statement, o2.statement);
    report.duplicates.push({ op1: o1, op2: o2, similarity: sim, isContradiction: false, crossDomain: o1.domain !== o2.domain, manual: true });
    console.log(`   🔧 ${o1.id} (${o1.domain}, c=${(o1.confidence ?? 0.5).toFixed(2)}) ↔ ${o2.id} (${o2.domain}, c=${(o2.confidence ?? 0.5).toFixed(2)}) [sim=${(sim * 100).toFixed(1)}% — below threshold but semantically equivalent]`);
  }
}

console.log("");
console.log("\n═══ SUMMARY ═══\n");
console.log(`   Duplicates found:      ${report.duplicates.length}`);
console.log(`   Contradictions found:   ${report.contradictions.length}`);
console.log(`   Cross-domain dupes:     ${report.crossDomain.length}`);
console.log(`   Test artifacts:         ${report.testArtifacts.length}`);
console.log(`   Low-value opinions:     ${lowValue.length}`);

// ─── Apply changes ──────────────────────────────────────────────────────────
if (!DRY_RUN) {
  console.log("\n═══ APPLYING CHANGES ═══\n");

  if (BACKUP) {
    const backupPath = OPINIONS_FILE.replace(".md", `.backup-${Date.now()}.md`);
    copyFileSync(OPINIONS_FILE, backupPath);
    console.log(`💾 Backup: ${backupPath}`);
  }

  let cleaned = [...opinions];
  let mergeCount = 0;
  let removeCount = 0;

  // Remove test artifacts
  for (const artifact of report.testArtifacts) {
    cleaned = cleaned.filter((o) => o.id !== artifact.id);
    removeCount++;
    console.log(`   🗑️  Removed test artifact: ${artifact.id}`);
  }

  // Merge duplicates (keep higher confidence, merge evidence)
  const merged = new Set();
  for (const dup of report.duplicates) {
    if (merged.has(dup.op1.id) || merged.has(dup.op2.id)) continue;

    const [keep, discard] =
      (dup.op1.confidence ?? 0.5) >= (dup.op2.confidence ?? 0.5)
        ? [dup.op1, dup.op2]
        : [dup.op2, dup.op1];

    // Find the actual objects in cleaned array
    const keepObj = cleaned.find((o) => o.id === keep.id);
    if (keepObj) {
      keepObj.evidence.supporting.push(...discard.evidence.supporting);
      keepObj.evidence.contradicting.push(...discard.evidence.contradicting);
      keepObj.lastUpdated = new Date().toISOString().split("T")[0];
    }

    cleaned = cleaned.filter((o) => o.id !== discard.id);
    merged.add(discard.id);
    mergeCount++;
    console.log(`   🔄 Merged ${discard.id} → ${keep.id} (kept c=${(keep.confidence ?? 0.5).toFixed(2)})`);
  }

  // Write result
  const output = serialize(cleaned);
  writeFileSync(OPINIONS_FILE, output, "utf-8");

  console.log(`\n✅ Done: ${removeCount} removed, ${mergeCount} merged. ${cleaned.length} opinions remaining.`);
} else {
  console.log(`\n💡 Run with --apply to execute changes.`);
  console.log(`   node scripts/purge-opinions.mjs --apply --backup`);
}
