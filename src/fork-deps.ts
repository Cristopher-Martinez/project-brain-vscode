/**
 * Fork Deps — Node modules provisioning for fork-based branch isolation.
 *
 * Provides a layered approach:
 * 1. **Junction** — `fork/node_modules` → `source/node_modules` (read existing deps)
 * 2. **Overlay** — `fork/.fork-deps/node_modules/` for fork-specific packages
 * 3. **NODE_PATH** — combines both so Node.js resolves from overlay first
 *
 * The source repo never sees the overlay directory.
 *
 * @module fork-deps
 */

import * as fs from "fs";
import * as path from "path";
import { log, logWarn } from "./logger";

// ─── Node Modules Provisioning (On-Demand) ──────────────────────────────────

/** Result of provisioning node_modules for a fork. */
export interface ForkDepsProvisionResult {
  ok: boolean;
  /** Junction to source's node_modules was created. */
  junctionCreated: boolean;
  /** Overlay directory for fork-specific packages. */
  overlayDir: string;
  /** NODE_PATH value that makes both layers visible. */
  nodePath: string;
}

/**
 * Provision node_modules for a fork using a layered approach:
 *
 * 1. **Junction** — `fork/node_modules` → `source/node_modules` (read existing deps)
 * 2. **Overlay** — `fork/.fork-deps/node_modules/` for fork-specific packages
 * 3. **NODE_PATH** — combines both so Node.js resolves from overlay first
 *
 * The source repo never sees the overlay. The junction gives read access
 * to all existing deps without copying hundreds of MB.
 *
 * To install fork-specific packages:
 *   `npm install --prefix .fork-deps <package>`
 *
 * @returns Provision result with overlay dir and NODE_PATH.
 */
export async function provisionForkNodeModules(
  repoRoot: string,
  forkPath: string,
): Promise<ForkDepsProvisionResult> {
  const sourceModules = path.join(repoRoot, "node_modules");
  const forkModules = path.join(forkPath, "node_modules");
  const overlayDir = path.join(forkPath, ".fork-deps");
  const overlayModules = path.join(overlayDir, "node_modules");

  let junctionCreated = false;

  // 1. Junction to source node_modules (if not already present)
  try {
    const sourceStat = await fs.promises.stat(sourceModules).catch(() => null);
    const targetStat = await fs.promises.stat(forkModules).catch(() => null);

    if (sourceStat?.isDirectory() && !targetStat) {
      const linkType = process.platform === "win32" ? "junction" : "dir";
      await fs.promises.symlink(sourceModules, forkModules, linkType);
      junctionCreated = true;
      log(`[ForkDeps] node_modules linked: ${forkModules} → ${sourceModules}`);
    } else if (targetStat) {
      junctionCreated = true; // already exists
      log("[ForkDeps] node_modules already present in fork");
    } else {
      log("[ForkDeps] No source node_modules — junction skipped");
    }
  } catch (err) {
    logWarn(`[ForkDeps] junction creation failed (non-fatal): ${err}`);
  }

  // 2. Create overlay directory for fork-specific packages
  try {
    await fs.promises.mkdir(overlayDir, { recursive: true });
    const pkgPath = path.join(overlayDir, "package.json");
    const exists = await fs.promises.stat(pkgPath).catch(() => null);
    if (!exists) {
      await fs.promises.writeFile(
        pkgPath,
        JSON.stringify({ name: "fork-overlay", private: true }, null, 2),
        "utf-8",
      );
    }
    log(`[ForkDeps] overlay dir ready: ${overlayDir}`);
  } catch (err) {
    logWarn(`[ForkDeps] overlay dir creation failed: ${err}`);
  }

  // 3. Build NODE_PATH: overlay first (higher priority), then junction
  const nodePath = [overlayModules, forkModules]
    .filter((p) => p)
    .join(path.delimiter);

  return { ok: junctionCreated, junctionCreated, overlayDir, nodePath };
}

// ─── Fork AGENTS.md ─────────────────────────────────────────────────────────

/** Options for generating the fork's AGENTS.md file. */
export interface ForkAgentsOptions {
  sessionId: string;
  branchName: string;
  originalBranch: string;
  forkPath: string;
  repoRoot: string;
  goal?: string;
  isolationAdvice?: string;
}

/**
 * Write an AGENTS.md file inside the fork so any agent knows:
 * - It's working in a fork, not the main repo
 * - What the fork's goal is
 * - How to install packages (overlay, not direct)
 * - Safety rules to protect the source repo
 */
export async function writeForkAgentsFile(
  opts: ForkAgentsOptions,
): Promise<void> {
  const goalLine = opts.goal
    ? `- **Goal**: ${opts.goal}`
    : "- **Goal**: (not specified)";

  const content = `# Fork Agent Instructions

> This file was auto-generated by Project Brain. It tells AI agents
> how to behave inside this fork.

## Context

- **This is a FORK** — not the main repository.
- **Session**: \`${opts.sessionId}\`
- **Branch**: \`${opts.branchName}\` (forked from \`${opts.originalBranch}\`)
${goalLine}
${opts.isolationAdvice ? `- **Isolation**: ${opts.isolationAdvice}` : ""}

## Rules

1. **All changes stay in this fork** until explicitly merged.
2. **Do NOT run \`npm install\` directly** — \`node_modules/\` is a junction to the source repo.
   - To install fork-specific packages: \`npm install --prefix .fork-deps <package>\`
   - The overlay \`.fork-deps/node_modules/\` is fork-only; the source can't see it.
3. **Do NOT modify files outside this fork directory.**
4. **Commit regularly** with descriptive messages.
5. **Source repo path**: \`${opts.repoRoot}\` — read-only reference, never write to it.

## Node Module Resolution

- **Existing deps**: resolved via junction \`node_modules/\` → source
- **Fork-specific deps**: install to \`.fork-deps/\`, set \`NODE_PATH\` if needed:
  \`\`\`
  NODE_PATH=.fork-deps/node_modules node your-script.js
  \`\`\`

## When You're Done

Call \`mergeFork\` to merge changes back to the source, or \`discardFork\` to discard them.
`;

  const agentsPath = path.join(opts.forkPath, "AGENTS.md");
  try {
    await fs.promises.writeFile(agentsPath, content, "utf-8");
    log(`[ForkDeps] AGENTS.md written: ${agentsPath}`);
  } catch (err) {
    logWarn(`[ForkDeps] Failed to write AGENTS.md (non-fatal): ${err}`);
  }
}
