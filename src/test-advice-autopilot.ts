import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, relative } from "path";
import * as ts from "typescript";
import { getLoopsDir } from "./brain-paths";
import { log, logError } from "./logger";
import { readTelemetrySummary } from "./test-advice-telemetry";
import type { ProjectTestContract } from "./test-pipeline-types";
import type { TestAdviceEntry } from "./test-advice-types";

const AUTOPILOT_DIR = "test-autopilot";
const CONTRACT_FILE = "test-contract.json";

export function attachAutopilotArtifacts(
  wsRoot: string,
  entries: TestAdviceEntry[],
): TestAdviceEntry[] {
  const contract = readTestContract(wsRoot);
  return entries.map((entry) => {
    if (!entry.needsTests || !entry.draftTest || !entry.suggestedTestPath) {
      return entry;
    }

    const targetPath = normalizeRelativePath(entry.suggestedTestPath);
    const draftPath = join(getLoopsDir(wsRoot), AUTOPILOT_DIR, targetPath);
    const runCommand = buildRunCommand(targetPath, contract);
    const telemetry = readTelemetrySummary(wsRoot, targetPath);
    const policy = selectConfidencePolicy(targetPath, runCommand);
    const validation = validateDraft(
      entry.draftTest,
      targetPath,
      runCommand,
      telemetry,
      policy,
    );
    const recommendationBand = pickRecommendationBand(validation, telemetry, policy);
    try {
      mkdirSync(dirname(draftPath), { recursive: true });
      writeFileSync(draftPath, buildDraftFile(targetPath, entry.draftTest), "utf8");
      log(`[TestAdvice] Autopilot draft ready: ${targetPath}`);
    } catch (err) {
      logError(`[TestAdvice] Failed to write autopilot draft: ${err}`);
      return entry;
    }

    return {
      ...entry,
      validation,
      recommendationBand,
      autopilotTargetPath: targetPath,
      autopilotDraftPath: normalizeRelativePath(relative(wsRoot, draftPath)),
      autopilotRunCommand: runCommand,
      autopilotShadowCommand:
        validation.syntaxOk && validation.targetPathOk && validation.runCommandOk
          ? buildShadowCommand(
              normalizeRelativePath(relative(wsRoot, draftPath)),
              targetPath,
              runCommand,
            )
          : undefined,
      autopilotApplyCommand:
        recommendationBand === "autopilot-safe"
          ? buildApplyCommand(
              normalizeRelativePath(relative(wsRoot, draftPath)),
              targetPath,
              runCommand,
            )
          : undefined,
    };
  });
}

function buildDraftFile(targetPath: string, draftTest: string): string {
  return [
    `// Autogenerated test draft for review. Target path: ${targetPath}`,
    "// Review behavior, imports, and fixtures before promoting this file into the repo.",
    "",
    draftTest.trim(),
    "",
  ].join("\n");
}

function readTestContract(wsRoot: string): ProjectTestContract | undefined {
  try {
    const contractPath = join(getLoopsDir(wsRoot), CONTRACT_FILE);
    if (!existsSync(contractPath)) {
      return undefined;
    }
    return JSON.parse(readFileSync(contractPath, "utf8")) as ProjectTestContract;
  } catch {
    return undefined;
  }
}

function buildRunCommand(
  targetPath: string,
  contract?: ProjectTestContract,
): string {
  if (targetPath.includes(".project-brain/hooks/scripts/__tests__/") || targetPath.includes(".github/hooks/scripts/__tests__/")) {
    return `node --test ${targetPath}`;
  }

  const testCommand = contract?.test;
  switch (contract?.framework) {
    case "vitest":
    case "jest":
      return testCommand ? `${testCommand} -- ${targetPath}` : `npm test -- ${targetPath}`;
    case "mocha":
      return `npx mocha ${targetPath}`;
    case "playwright":
      return `npx playwright test ${targetPath}`;
    case "pytest":
      return `pytest ${targetPath}`;
    default:
      return testCommand ?? `npm test -- ${targetPath}`;
  }
}

function buildApplyCommand(
  draftPath: string,
  targetPath: string,
  runCommand: string,
): string {
  return `node scripts/test-autopilot.mjs apply "${draftPath}" "${targetPath}" "${runCommand}"`;
}

function buildShadowCommand(
  draftPath: string,
  targetPath: string,
  runCommand: string,
): string {
  return `node scripts/test-autopilot.mjs shadow "${draftPath}" "${targetPath}" "${runCommand}"`;
}

function validateDraft(
  draftTest: string,
  targetPath: string,
  runCommand: string,
  telemetry: { totalRuns: number; recentSuccesses: number; recentFailures: number },
  policy: { label: string; requiredSuccesses: number },
) {
  const transpiled = ts.transpileModule(draftTest, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
    },
    reportDiagnostics: true,
  });
  const syntaxOk = !transpiled.diagnostics || transpiled.diagnostics.length === 0;
  const targetPathOk = /\.(test|spec)\.(ts|tsx|js|jsx|mjs|cjs)$/.test(targetPath);
  const runCommandOk = Boolean(runCommand && runCommand.includes(targetPath));
  const notes = [];
  if (!syntaxOk) notes.push("draft has syntax diagnostics");
  if (!targetPathOk) notes.push("target path does not look like a test file");
  if (!runCommandOk) notes.push("run command is not target-aware");
  if (telemetry.totalRuns === 0 && syntaxOk && targetPathOk && runCommandOk) {
    notes.push(
      `run shadow autopilot to establish ${policy.requiredSuccesses} clean run(s) for ${policy.label}`,
    );
  }
  if (
    telemetry.recentFailures === 0 &&
    telemetry.recentSuccesses > 0 &&
    telemetry.recentSuccesses < policy.requiredSuccesses
  ) {
    notes.push(
      `history is promising but incomplete: ${telemetry.recentSuccesses}/${policy.requiredSuccesses} clean run(s) for ${policy.label}`,
    );
  }
  if (telemetry.totalRuns > 0 && telemetry.recentFailures > telemetry.recentSuccesses) {
    notes.push("recent autopilot runs for this target pattern have failed");
  }
  return {
    syntaxOk,
    targetPathOk,
    runCommandOk,
    policyLabel: policy.label,
    requiredSuccesses: policy.requiredSuccesses,
    notes,
  };
}

function pickRecommendationBand(
  validation: { syntaxOk: boolean; targetPathOk: boolean; runCommandOk: boolean },
  telemetry: { totalRuns: number; recentSuccesses: number; recentFailures: number },
  policy: { label: string; requiredSuccesses: number },
): "advisory" | "draft-only" | "autopilot-safe" {
  if (!validation.syntaxOk || !validation.targetPathOk || !validation.runCommandOk) {
    return "draft-only";
  }
  if (telemetry.totalRuns === 0) {
    return "advisory";
  }
  if (telemetry.recentFailures > telemetry.recentSuccesses) {
    return "draft-only";
  }
  if (telemetry.recentSuccesses < policy.requiredSuccesses) {
    return "advisory";
  }
  return "autopilot-safe";
}

function selectConfidencePolicy(
  targetPath: string,
  runCommand: string,
): { label: string; requiredSuccesses: number } {
  if (targetPath.includes(".project-brain/hooks/scripts/__tests__/") || targetPath.includes(".github/hooks/scripts/__tests__/")) {
    return { label: "hook tests", requiredSuccesses: 1 };
  }
  if (/playwright/i.test(runCommand)) {
    return { label: "playwright/e2e", requiredSuccesses: 3 };
  }
  if (targetPath.includes("saas/node-server/")) {
    return { label: "saas backend", requiredSuccesses: 2 };
  }
  if (/vitest|jest|npm test/i.test(runCommand)) {
    return { label: "app/unit tests", requiredSuccesses: 2 };
  }
  return { label: "default", requiredSuccesses: 2 };
}

function normalizeRelativePath(filePath: string): string {
  return filePath.replace(/\\/g, "/").replace(/^\.\//, "");
}