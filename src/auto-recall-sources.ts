/**
 * Auto-Recall Data Sources — standalone functions for gathering context.
 *
 * Extracted from AutoRecall class to keep each file under 400 lines.
 * These functions read BOOT.md, knowledge summaries, skill catalogs,
 * and recent sessions — all the raw data that gets assembled by AutoRecall.
 */

import * as fs from "fs";
import * as path from "path";
import { sanitizeContent } from "./security-utils";

// ─── Types ──────────────────────────────────────────────────────────────────

/** Minimal SkillManager-like interface for reading available skills. */
export interface SkillManagerLike {
  getAll(): Array<{
    manifest: { name: string; description: string };
    source: string;
  }>;
}

/** Minimal SessionDB-like interface for recent session queries. */
export interface SessionDBLike {
  getRecentSummaries(
    limit: number,
  ): Promise<Array<{ sourceFile?: string; date: string }>>;
}

/** Boot context cache entry. */
export interface BootCache {
  content: string | null;
  time: number;
}

// ─── Constants ──────────────────────────────────────────────────────────────

const BOOT_CACHE_TTL = 120_000; // 2 minutes
const MAX_BOOT_CHARS = 1500;
const MAX_KNOWLEDGE_CHARS = 2000;

// ─── Sanitization ───────────────────────────────────────────────────────────

/** Sanitize content before injecting into LLM context. */
export function sanitizeRecallContent(text: string): string {
  return sanitizeContent(text);
}

// ─── Boot Context ───────────────────────────────────────────────────────────

/**
 * Read BOOT.md (compact project snapshot). Uses cache with TTL.
 * Returns cached content if still fresh, otherwise reads from disk.
 */
export function readBootContext(
  memoryPath: string,
  cache: BootCache,
): { content: string | null; cache: BootCache } {
  const now = Date.now();
  if (cache.content && now - cache.time < BOOT_CACHE_TTL) {
    return { content: cache.content, cache };
  }

  const bootPath = path.join(memoryPath, "BOOT.md");
  if (!fs.existsSync(bootPath)) return { content: null, cache };

  try {
    const raw = fs.readFileSync(bootPath, "utf-8");
    const content = raw.substring(0, MAX_BOOT_CHARS).trim();
    return { content, cache: { content, time: now } };
  } catch {
    return { content: null, cache };
  }
}

// ─── Knowledge Summary ──────────────────────────────────────────────────────

/**
 * Read pre-computed knowledge summary or fallback to extracting
 * recent entries from memory files (04_LEARNINGS, 05_TROUBLESHOOTING, 11_PREFS).
 */
export function readKnowledgeSummary(memoryPath: string): string | null {
  // Try pre-computed summary first (generated by LearningRouter)
  const summaryPath = path.join(
    memoryPath,
    "sessions",
    "knowledge-summary.txt",
  );
  if (fs.existsSync(summaryPath)) {
    try {
      const content = fs.readFileSync(summaryPath, "utf-8");
      if (content.trim().length > 20) {
        return content.substring(0, MAX_KNOWLEDGE_CHARS).trim();
      }
    } catch {
      // Fall through to manual extraction
    }
  }

  return extractKnowledgeFromFiles(memoryPath);
}

/** Fallback: extract last entries from memory files. */
function extractKnowledgeFromFiles(memoryPath: string): string | null {
  const parts: string[] = [];
  let budget = MAX_KNOWLEDGE_CHARS;

  // Programming preferences (small file, high value)
  const prefsPath = path.join(memoryPath, "11_PROGRAMMING_PREFS.md");
  if (fs.existsSync(prefsPath)) {
    try {
      const prefs = fs
        .readFileSync(prefsPath, "utf-8")
        .substring(0, 600)
        .trim();
      if (prefs.length > 30) {
        parts.push("## Preferences\n" + prefs);
        budget -= prefs.length + 20;
      }
    } catch {
      /* skip */
    }
  }

  // Last 5 learnings
  const learningsPath = path.join(memoryPath, "04_LEARNINGS.md");
  if (budget > 200 && fs.existsSync(learningsPath)) {
    try {
      const raw = fs.readFileSync(learningsPath, "utf-8");
      const sections = raw.split(/^## /m).filter(Boolean);
      const last5 = sections.slice(-5);
      const learnings = last5
        .map((s) => "• " + s.split("\n")[0].trim())
        .join("\n");
      if (learnings.length > 20) {
        const capped = learnings.substring(0, Math.min(budget - 100, 800));
        parts.push("## Recent Learnings\n" + capped);
        budget -= capped.length + 25;
      }
    } catch {
      /* skip */
    }
  }

  // Last 3 troubleshooting entries
  const troublePath = path.join(memoryPath, "05_TROUBLESHOOTING.md");
  if (budget > 200 && fs.existsSync(troublePath)) {
    try {
      const raw = fs.readFileSync(troublePath, "utf-8");
      const sections = raw.split(/^## /m).filter(Boolean);
      const last3 = sections.slice(-3);
      const trouble = last3
        .map((s) => "• " + s.split("\n")[0].trim())
        .join("\n");
      if (trouble.length > 20) {
        const capped = trouble.substring(0, Math.min(budget, 600));
        parts.push("## Known Issues\n" + capped);
      }
    } catch {
      /* skip */
    }
  }

  return parts.length > 0 ? parts.join("\n\n") : null;
}

// ─── Skill Catalog ──────────────────────────────────────────────────────────

/**
 * Read vault context (labels + instructions, NO values) for agent awareness.
 * Returns a compact summary so agents know what credentials are available.
 */
export function readVaultSummary(workspaceRoot: string): string | null {
  const vaultPath = path.join(
    workspaceRoot,
    ".project-brain",
    "vault",
    "project.brain.vault.env",
  );
  if (!fs.existsSync(vaultPath)) return null;

  try {
    const raw = fs.readFileSync(vaultPath, "utf-8");
    // Extract labels and instructions only (never raw secrets into context)
    const headers: string[] = [];
    const lines = raw.split(/\r?\n/);
    let currentLabel = "";
    let currentInstr = "";
    let keys: string[] = [];

    for (const line of lines) {
      const headerMatch = line.trim().match(/^##\s+\[(.+)\]\s*$/);
      if (headerMatch) {
        if (currentLabel) {
          const desc = currentInstr ? ` — ${currentInstr}` : "";
          const keyList = keys.length > 0 ? ` (${keys.join(", ")})` : "";
          headers.push(`• **${currentLabel}**${desc}${keyList}`);
        }
        currentLabel = headerMatch[1];
        currentInstr = "";
        keys = [];
        continue;
      }

      const instrMatch = line.trim().match(/^#\s*Instructions?:\s*(.*)$/i);
      if (instrMatch && currentLabel) {
        currentInstr = instrMatch[1].substring(0, 80);
        continue;
      }

      const kvMatch = line.trim().match(/^([A-Za-z_][A-Za-z0-9_./-]*)=/);
      if (kvMatch && currentLabel) {
        keys.push(kvMatch[1]);
      }
    }

    // Flush last
    if (currentLabel) {
      const desc = currentInstr ? ` — ${currentInstr}` : "";
      const keyList = keys.length > 0 ? ` (${keys.join(", ")})` : "";
      headers.push(`• **${currentLabel}**${desc}${keyList}`);
    }

    if (headers.length === 0) return null;

    return [
      "🔐 **Vault** (credential store):",
      ...headers,
      "",
      "⚠️ **MANDATORY**: When ANY task requires credentials, API keys, tokens, passwords, or secrets — ALWAYS call `readVaultEntry` first (no label → list all, with label → get secrets). NEVER ask the user for credentials without checking the vault first.",
    ].join("\n");
  } catch {
    return null;
  }
}

// ─── Skill Catalog (original) ───────────────────────────────────────────────

/**
 * Build a compact skill catalog for injection.
 * Tries SkillManager first (includes remote skills),
 * falls back to filesystem scan of .project-brain/memory/skills/.
 */
export function readSkillCatalog(
  memoryPath: string,
  skillManager?: SkillManagerLike | null,
): string | null {
  const skills: { name: string; desc: string; source: string }[] = [];

  // Try SkillManager first (includes remote/marketplace skills)
  if (skillManager && typeof skillManager.getAll === "function") {
    try {
      const all = skillManager.getAll();
      for (const s of all) {
        const desc = (s.manifest.description || "").substring(0, 100);
        skills.push({
          name: s.manifest.name,
          desc: desc || "(no description)",
          source: s.source,
        });
      }
    } catch {
      // Fall through to filesystem scan
    }
  }

  // Fallback: filesystem scan (works without SaaS/SkillManager)
  if (skills.length === 0) {
    const skillsDir = path.join(memoryPath, "skills");
    if (!fs.existsSync(skillsDir)) return null;

    try {
      const entries = fs.readdirSync(skillsDir, { withFileTypes: true });
      for (const entry of entries) {
        if (!entry.isDirectory()) continue;
        const skillPath = path.join(skillsDir, entry.name, "SKILL.md");
        if (!fs.existsSync(skillPath)) continue;

        const head = fs.readFileSync(skillPath, "utf-8").substring(0, 500);
        const descMatch = head.match(/description:\s*(.+)/);
        const desc = descMatch?.[1]?.trim() ?? "";

        skills.push({
          name: entry.name,
          desc: desc ? desc.substring(0, 100) : "(no description)",
          source: "local",
        });
      }
    } catch {
      return null;
    }
  }

  if (skills.length === 0) return null;

  // Group by source for clarity
  const local = skills.filter((s) => s.source !== "remote");
  const remote = skills.filter((s) => s.source === "remote");

  const lines: string[] = [];
  if (local.length > 0) {
    lines.push(...local.map((s) => `- **${s.name}**: ${s.desc}`));
  }
  if (remote.length > 0) {
    lines.push(`\n📡 Remote skills (${remote.length}):`);
    lines.push(...remote.map((s) => `- **${s.name}**: ${s.desc}`));
  }

  return `Use findSkill("name") to load a skill before starting a matching task.\n${lines.join("\n")}`;
}

// ─── Recent Sessions ────────────────────────────────────────────────────────

/** Read recent sessions from filesystem (today + yesterday). */
export function readRecentSessionsFromFs(memoryPath: string): string | null {
  const sessionsDir = path.join(memoryPath, "sessions");
  if (!fs.existsSync(sessionsDir)) return null;

  try {
    const today = new Date();
    const yesterday = new Date(today);
    yesterday.setDate(yesterday.getDate() - 1);

    const todayStr = today.toISOString().split("T")[0];
    const yesterdayStr = yesterday.toISOString().split("T")[0];

    const files = fs
      .readdirSync(sessionsDir)
      .filter(
        (f) =>
          f.endsWith(".md") &&
          (f.startsWith(todayStr) || f.startsWith(yesterdayStr)),
      )
      .sort()
      .reverse();

    if (files.length === 0) return null;

    const lines = files.map((f) => `- ${f}`);
    return `Recent sessions (today/yesterday):\n${lines.join("\n")}`;
  } catch {
    return null;
  }
}

/** Read recent sessions from SQLite (preferred), falling back to filesystem. */
export async function readRecentSessionsAsync(
  memoryPath: string,
  sessionDb?: SessionDBLike | null,
): Promise<string | null> {
  if (sessionDb) {
    try {
      const rows = await sessionDb.getRecentSummaries(2);
      if (rows.length > 0) {
        const lines = rows
          .slice(0, 10)
          .map((r) => `- ${r.sourceFile || r.date}`);
        return `Recent sessions (SQLite):\n${lines.join("\n")}`;
      }
    } catch {
      /* fall through */
    }
  }

  return readRecentSessionsFromFs(memoryPath);
}

// ─── Context Assembly ───────────────────────────────────────────────────────

/** Tagged section for context injection. */
export interface ContextSection {
  tag: string;
  content: string;
}

/** Assemble context sections into a single string with XML-like tags. */
export function assembleContext(sections: ContextSection[]): string {
  if (sections.length === 0) return "";
  return sections
    .map((s) => `<${s.tag}>\n${sanitizeRecallContent(s.content)}\n</${s.tag}>`)
    .join("\n");
}
