import { existsSync, readFileSync, writeFileSync } from "fs";
import { dirname, join, resolve } from "path";
import {
  countUniqueInvariants,
  detectImpactInconsistency,
  detectInflation,
  parseInvariants,
  validateInvariantId,
} from "./invariants-parser";
import { log, logWarn } from "./logger";
import { PROJECT_BRAIN_DIR } from "./brain-paths";
import type {
  CoreModuleEntry,
  InvariantEntry,
  InvariantRecord,
  InvariantSyncResult,
  InvariantTier,
  ProjectTestContract,
} from "./test-pipeline-types";
const INVARIANTS_FILE = "INVARIANTS.md";
const MAX_INVARIANTS_WARNING = 50;

/** Resolve the INVARIANTS.md path inside .project-brain/ to avoid root contamination. */
function invariantsPath(wsRoot: string): string {
  return join(wsRoot, PROJECT_BRAIN_DIR, INVARIANTS_FILE);
}

/** Parse INVARIANTS.md into InvariantRecord[]. */
export function readInvariantsDoc(wsRoot: string): InvariantRecord[] {
  const filePath = invariantsPath(wsRoot);
  // Backward compat: check legacy root-level location too
  const legacyPath = join(wsRoot, INVARIANTS_FILE);
  const effectivePath = existsSync(filePath) ? filePath : existsSync(legacyPath) ? legacyPath : filePath;
  if (!existsSync(effectivePath)) {
    return [];
  }

  const content = readFileSync(effectivePath, "utf-8");
  const records: InvariantRecord[] = [];
  let currentTier: InvariantTier = "non-core";

  for (const line of content.split("\n")) {
    // Detect section headers
    if (/^## Core\b/i.test(line)) {
      currentTier = "core";
      continue;
    }
    if (/^## Non-core\b/i.test(line)) {
      currentTier = "non-core";
      continue;
    }

    // Parse invariant lines: - `id` — description | Impact: text | Files: f1,f2
    const match = line.match(
      /^- `([a-z0-9][a-z0-9_-]*)` — (.+?) \| Impact: (.+?) \| Files: (.+)$/,
    );
    if (!match) {
      continue;
    }

    records.push({
      id: match[1],
      description: match[2].trim(),
      impact: match[3].trim(),
      tier: currentTier,
      files: match[4].split(",").map((f) => f.trim()),
      addedAt: "", // Not stored in md format
    });
  }

  return records;
}

/** Write INVARIANTS.md from records. */
export function writeInvariantsDoc(
  wsRoot: string,
  records: InvariantRecord[],
  warnings?: string[],
): void {
  const core = records.filter((r) => r.tier === "core");
  const nonCore = records.filter((r) => r.tier === "non-core");

  const lines: string[] = [
    "# Invariants",
    "",
    "<!-- Auto-generated by Project Brain T1. Do not edit manually. -->",
    `<!-- Last sync: ${new Date().toISOString()} -->`,
    "",
    "## Core (block merge if not covered)",
    "",
  ];

  if (core.length === 0) {
    lines.push("_No core invariants detected yet._", "");
  } else {
    for (const r of core) {
      lines.push(formatRecord(r));
    }
    lines.push("");
  }

  lines.push("## Non-core (tracked, non-blocking)", "");

  if (nonCore.length === 0) {
    lines.push("_No non-core invariants detected yet._", "");
  } else {
    for (const r of nonCore) {
      lines.push(formatRecord(r));
    }
    lines.push("");
  }

  if (warnings?.length) {
    lines.push("## ⚠️ Warnings", "", ...warnings.map((w) => `- ${w}`), "");
  }
  writeFileSync(invariantsPath(wsRoot), lines.join("\n"), "utf-8");
  log(
    `[Invariants] Wrote ${INVARIANTS_FILE}: ${core.length} core, ${nonCore.length} non-core`,
  );
}

function formatRecord(r: InvariantRecord): string {
  return `- \`${r.id}\` — ${r.description} | Impact: ${r.impact} | Files: ${r.files.join(", ")}`;
}

/** Extract import/require paths from a test file's content. */
function extractImports(content: string): string[] {
  const imports: string[] = [];
  // ES import: import { x } from './path'  or  import x from './path'
  const esImportRe = /import\s+(?:[\s\S]*?from\s+)?['"]([^'"]+)['"]/g;
  // CJS require: require('./path')
  const cjsRequireRe = /require\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
  // Python: from module import x  or  import module
  const pyImportRe = /(?:from\s+(\S+)\s+import|import\s+(\S+))/g;

  let m;
  while ((m = esImportRe.exec(content)) !== null) {
    imports.push(m[1]);
  }
  while ((m = cjsRequireRe.exec(content)) !== null) {
    imports.push(m[1]);
  }
  while ((m = pyImportRe.exec(content)) !== null) {
    imports.push(m[1] ?? m[2]);
  }

  return imports;
}

/** Normalize an import path to compare against coreModule paths. */
function normalizeImportPath(
  importPath: string,
  testFile: string,
  wsRoot: string,
): string {
  // Relative import: resolve relative to test file location
  if (importPath.startsWith(".")) {
    const testDir = dirname(join(wsRoot, testFile));
    const resolved = resolve(testDir, importPath);
    // Remove wsRoot prefix and normalize
    return resolved.replace(wsRoot, "").replace(/\\/g, "/").replace(/^\//, "");
  }
  return importPath;
}

/**
 * Determine if an invariant is core (blocking) or non-core.
 * Uses import analysis: reads the test file and checks if it imports a core module.
 * Falls back to path-based heuristic if imports can't be analyzed.
 */
export function classifyTier(
  entry: InvariantEntry,
  coreModules: CoreModuleEntry[],
  wsRoot?: string,
): InvariantTier {
  if (!wsRoot || coreModules.length === 0) {
    return "non-core";
  }

  const corePaths = coreModules.map((m) => m.path.replace(/\\/g, "/"));

  // Strategy 1: Import analysis (strong signal)
  const testFilePath = join(wsRoot, entry.file);
  try {
    const content = readFileSync(testFilePath, "utf-8");
    const imports = extractImports(content);

    for (const imp of imports) {
      const normalized = normalizeImportPath(imp, entry.file, wsRoot);
      // Check if any import resolves to a core module path
      for (const corePath of corePaths) {
        const coreBase = corePath.replace(
          /\.(ts|js|tsx|jsx|mjs|cjs|py|go|rs)$/,
          "",
        );
        const impBase = normalized.replace(
          /\.(ts|js|tsx|jsx|mjs|cjs|py|go|rs)$/,
          "",
        );
        if (impBase === coreBase || normalized.includes(coreBase)) {
          return "core";
        }
      }
    }
  } catch {
    // Can't read test file — fall through to path heuristic
  }

  // Strategy 2: Path heuristic (weak fallback)
  for (const corePath of corePaths) {
    const base = dirname(corePath);
    if (entry.file.startsWith(base) || entry.file.includes(base)) {
      return "core";
    }
  }

  return "non-core";
}

import { appendHistory } from "./invariants-queries";

/**
 * Full sync: parse test files → compare with INVARIANTS.md → update.
 * Returns a summary of what changed.
 */
export function syncInvariants(
  wsRoot: string,
  contract: ProjectTestContract,
): InvariantSyncResult {
  const parsed = parseInvariants(wsRoot, contract.invariantsPattern);
  const existing = readInvariantsDoc(wsRoot);
  const warnings: string[] = [];

  // Validate quality + orphan detection
  for (const entry of parsed) {
    const validation = validateInvariantId(entry.id);
    if (!validation.valid) {
      warnings.push(`${entry.file}: ${validation.reason}`);
    }
    if (!entry.testName) {
      warnings.push(
        `⚠ "${entry.id}" en ${entry.file} sin test function — posible teatro semántico`,
      );
    }
  }

  // Anti-inflation checks
  const uniqueCount = countUniqueInvariants(parsed);
  if (uniqueCount > MAX_INVARIANTS_WARNING) {
    warnings.push(
      `${uniqueCount} invariantes únicas detectadas (>${MAX_INVARIANTS_WARNING}) — revisión recomendada`,
    );
  }

  const inflated = detectInflation(parsed);
  for (const id of inflated) {
    warnings.push(`"${id}" aparece en >5 test files — posible inflación`);
  }

  // Impact inconsistency check
  const inconsistent = detectImpactInconsistency(parsed);
  for (const { id, impacts } of inconsistent) {
    warnings.push(
      `⚠ "${id}" tiene impactos inconsistentes: ${impacts.map((i) => `"${i}"`).join(" vs ")}`,
    );
  }

  // Build new records map
  const parsedMap = new Map<
    string,
    { entries: InvariantEntry[]; tier: InvariantTier }
  >();
  for (const entry of parsed) {
    const tier = classifyTier(entry, contract.coreModules, wsRoot);
    if (!parsedMap.has(entry.id)) {
      parsedMap.set(entry.id, { entries: [], tier });
    }
    parsedMap.get(entry.id)!.entries.push(entry);
    // Promote to core if any occurrence is core
    if (tier === "core") {
      parsedMap.get(entry.id)!.tier = "core";
    }
  }

  // Detect added/removed/updated
  const existingMap = new Map(existing.map((r) => [r.id, r]));
  const added: InvariantEntry[] = [];
  const updated: InvariantEntry[] = [];
  const newRecords: InvariantRecord[] = [];

  for (const [id, data] of parsedMap) {
    const files = [...new Set(data.entries.map((e) => e.file))];
    const first = data.entries[0];

    const record: InvariantRecord = {
      id,
      description: first.description,
      impact: first.impact,
      tier: data.tier,
      files,
      addedAt: existingMap.get(id)?.addedAt ?? new Date().toISOString(),
    };

    if (!existingMap.has(id)) {
      added.push(first);
      appendHistory(wsRoot, {
        action: "added",
        invariantId: id,
        timestamp: new Date().toISOString(),
      });
    } else {
      const old = existingMap.get(id)!;
      if (
        old.description !== record.description ||
        old.impact !== record.impact
      ) {
        updated.push(first);
        appendHistory(wsRoot, {
          action: "modified",
          invariantId: id,
          timestamp: new Date().toISOString(),
          previousValue: { description: old.description, impact: old.impact },
        });
      }
    }

    newRecords.push(record);
  }

  // Detect removed
  const removed: InvariantRecord[] = [];
  for (const old of existing) {
    if (!parsedMap.has(old.id)) {
      removed.push(old);
      appendHistory(wsRoot, {
        action: "deleted",
        invariantId: old.id,
        timestamp: new Date().toISOString(),
        previousValue: old,
      });
      logWarn(
        `[Invariants] DELETED: ${old.id} — was in ${old.files.join(", ")}`,
      );
    }
  }

  const coreCount = newRecords.filter((r) => r.tier === "core").length;

  // Tier downgrade detection: core → non-core indicates import structure changed
  for (const old of existing) {
    if (old.tier === "core") {
      const newRec = newRecords.find((r) => r.id === old.id);
      if (newRec && newRec.tier === "non-core") {
        warnings.push(
          `⚠ "${old.id}" degradado de core → non-core (¿se eliminó import de módulo core?)`,
        );
        appendHistory(wsRoot, {
          action: "modified",
          invariantId: old.id,
          timestamp: new Date().toISOString(),
          justification: "tier downgrade: core → non-core",
          previousValue: { tier: "core" },
        });
      }
    }
  }

  // Uncovered core modules: per-module check
  for (const cm of contract.coreModules) {
    const mp = cm.path.replace(/\\/g, "/");
    if (
      !newRecords.some(
        (r) =>
          r.tier === "core" && r.files.some((f) => f.includes(dirname(mp))),
      )
    ) {
      warnings.push(`🔴 Módulo core "${mp}" sin invariantes`);
    }
  }

  // Write updated INVARIANTS.md (after all warnings collected)
  writeInvariantsDoc(wsRoot, newRecords, warnings);
  // Log warnings
  for (const w of warnings) {
    logWarn(`[Invariants] ⚠ ${w}`);
  }

  return {
    added,
    removed,
    updated,
    total: newRecords.length,
    coreCount,
    warnings,
  };
}

