/**
 * Opinion Persistence — Markdown serialization/deserialization for opinions.
 *
 * Extracted from opinion-bank.ts to comply with 400-line limit.
 * Pure functions: serialize opinions to Markdown, parse Markdown to opinions.
 */

import type { Opinion } from "./opinion-types";

// ─── Serialization ──────────────────────────────────────────────────────────

/** Serialize an array of opinions to the Markdown format used in 14_OPINIONS.md. */
export function serializeOpinions(opinions: Opinion[]): string {
  const lines: string[] = [
    "# Opinion Bank",
    "",
    `> Auto-generated by Project Brain. ${opinions.length} opinions tracked.`,
    `> Last updated: ${new Date().toISOString().split("T")[0]}`,
    "",
  ];

  // Group by domain
  const grouped = new Map<string, Opinion[]>();
  for (const op of opinions) {
    const list = grouped.get(op.domain) || [];
    list.push(op);
    grouped.set(op.domain, list);
  }

  for (const [domain, ops] of grouped) {
    lines.push(`## ${domain}`);
    lines.push("");

    for (const op of ops.sort((a, b) => b.confidence - a.confidence)) {
      lines.push(`### ${op.id}`);
      lines.push("");
      lines.push(`- **Statement**: ${op.statement}`);
      lines.push(`- **Confidence**: ${op.confidence.toFixed(2)}`);
      lines.push(`- **Created**: ${op.createdAt}`);
      lines.push(`- **Updated**: ${op.lastUpdated}`);

      if (op.evidence.supporting.length > 0) {
        lines.push(`- **Supporting**: ${op.evidence.supporting.join("; ")}`);
      }
      if (op.evidence.contradicting.length > 0) {
        lines.push(
          `- **Contradicting**: ${op.evidence.contradicting.join("; ")}`,
        );
      }
      lines.push("");
    }
  }

  return lines.join("\n");
}

// ─── Parsing ────────────────────────────────────────────────────────────────

/** Parse the Markdown format of 14_OPINIONS.md into an array of Opinion objects. */
export function parseOpinions(content: string): Opinion[] {
  const opinions: Opinion[] = [];
  const lines = content.split("\n");
  let current: Partial<Opinion> | null = null;
  let currentDomain = "general";

  for (const line of lines) {
    // Domain header: ## architecture
    const domainMatch = line.match(/^## (\w+)/);
    if (domainMatch) {
      currentDomain = domainMatch[1];
      continue;
    }

    // Opinion header: ### op_xxxx
    const idMatch = line.match(/^### (op_\w+)/);
    if (idMatch) {
      if (current && current.id && current.statement) {
        opinions.push(fillOpinionDefaults(current, currentDomain));
      }
      current = { id: idMatch[1], domain: currentDomain };
      continue;
    }

    if (!current) continue;

    // Parse fields
    const stmtMatch = line.match(/^- \*\*Statement\*\*: (.+)/);
    if (stmtMatch) {
      current.statement = stmtMatch[1];
      continue;
    }

    const confMatch = line.match(/^- \*\*Confidence\*\*: ([\d.]+)/);
    if (confMatch) {
      current.confidence = parseFloat(confMatch[1]);
      continue;
    }

    const createdMatch = line.match(/^- \*\*Created\*\*: (.+)/);
    if (createdMatch) {
      current.createdAt = createdMatch[1];
      continue;
    }

    const updatedMatch = line.match(/^- \*\*Updated\*\*: (.+)/);
    if (updatedMatch) {
      current.lastUpdated = updatedMatch[1];
      continue;
    }

    const supMatch = line.match(/^- \*\*Supporting\*\*: (.+)/);
    if (supMatch) {
      current.evidence = current.evidence || {
        supporting: [],
        contradicting: [],
      };
      current.evidence.supporting = supMatch[1].split("; ").filter(Boolean);
      continue;
    }

    const conMatch = line.match(/^- \*\*Contradicting\*\*: (.+)/);
    if (conMatch) {
      current.evidence = current.evidence || {
        supporting: [],
        contradicting: [],
      };
      current.evidence.contradicting = conMatch[1].split("; ").filter(Boolean);
      continue;
    }
  }

  // Last one
  if (current && current.id && current.statement) {
    opinions.push(fillOpinionDefaults(current, currentDomain));
  }

  return opinions;
}

/** Fill default values for partially parsed opinions. */
export function fillOpinionDefaults(
  partial: Partial<Opinion>,
  domain: string,
): Opinion {
  const now = new Date().toISOString().split("T")[0];
  return {
    id: partial.id || `op_${Math.random().toString(36).substring(2, 8)}`,
    statement: partial.statement || "",
    confidence: partial.confidence ?? 0.5,
    domain: partial.domain || domain,
    evidence: partial.evidence || { supporting: [], contradicting: [] },
    createdAt: partial.createdAt || now,
    lastUpdated: partial.lastUpdated || now,
  };
}
