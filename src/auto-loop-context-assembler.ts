export interface ContextAssemblerInput {
  objective: string;
  activeSynthesis: BridgeSynthesis;
  taskMemory: BridgeTaskMemoryData;
  retrievalChunks: string[];
  pmChatHistory: PmChatMessage[];
  conversationRagChunks?: string[];
  responseLanguage?: string;
  identityPrompt?: string;
  userMessage: string;
  budget: BridgeTokenBudget;
  workerLoopSessionId?: string;
  workerLoopState?: "active" | "awaiting" | "completed" | "error" | "disconnected";
  canDispatchFeedback?: boolean;
  bitacoraContext?: string;
  projectMemoryContext?: string;
}

/**
 * Assemble a compact PMRequestInput from raw session data.
 * Applies budget constraints to prevent context blowup.
 */
export function assembleContext(
  input: ContextAssemblerInput
): PMRequestInput {
  const {
    objective,
    activeSynthesis,
    taskMemory,
    retrievalChunks,
    pmChatHistory,
    userMessage,
    conversationRagChunks = [],
    responseLanguage,
    workerLoopSessionId,
    workerLoopState,
    canDispatchFeedback,
    bitacoraContext,
    projectMemoryContext,
  } = input;

  // Enforce hard ceilings on budget
  const budget = clampBudget(input.budget);

  // Capture pre-trimming sizes
  const pre = {
    synthesisChars: activeSynthesis.content.length,
    historyCount: pmChatHistory.length,
    retrievalCount: retrievalChunks.length,
  };

  const decisionsSummary = buildDecisionsSummary(taskMemory);
  const allChunks = [...retrievalChunks, ...conversationRagChunks];
  const trimmedRetrieval = trimRetrievalPack(allChunks, budget);
  const trimmedHistory = trimChatHistory(pmChatHistory, budget);
  const trimmedSynthesis = trimToCharBudget(
    activeSynthesis.content,
    Math.floor(budget.maxContextChars * 0.4)
  );

  const assembled: PMRequestInput = {
    objective: trimToCharBudget(objective, 500),
    activeSynthesis: {
      ...activeSynthesis,
      content: trimmedSynthesis,
    },
    decisionsSummary: trimToCharBudget(decisionsSummary, 2000),
    retrievalPack: trimmedRetrieval,
    pmChatHistory: trimmedHistory,
    userMessage,
    budget,
    responseLanguage,
    workerLoopSessionId,
    workerLoopState,
    canDispatchFeedback,
    identityPrompt: input.identityPrompt,
    bitacoraContext: bitacoraContext ? trimToCharBudget(bitacoraContext, Math.floor(budget.maxContextChars * 0.10)) : undefined,
    projectMemoryContext: projectMemoryContext ? trimToCharBudget(projectMemoryContext, Math.floor(budget.maxContextChars * 0.15)) : undefined,
  };

  const totalChars = estimateChars(assembled);

  // Log truncation metrics
  const metrics = buildTruncationMetrics(
    pre,
    {
      synthesisChars: trimmedSynthesis.length,
      historyCount: trimmedHistory.length,
      retrievalCount: trimmedRetrieval.length,
      totalChars,
    },
    budget
  );
  logTruncationMetrics(input.budget.consumedTurns.toString(), metrics);

  log(
    `[ContextAssembler] Built brief: ${totalChars} chars, ` +
      `${trimmedRetrieval.length} chunks, ${trimmedHistory.length} history msgs`
  );

  return assembled;
}

