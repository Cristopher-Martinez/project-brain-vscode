/**
 * Trim retrieval chunks to fit within maxRetrievedChunks budget.
 * Prioritizes shorter, more relevant chunks (assumes pre-sorted by relevance).
 */
function trimRetrievalPack(
  chunks: string[],
  budget: BridgeTokenBudget
): string[] {
  const maxChunks = budget.maxRetrievedChunks;
  if (chunks.length <= maxChunks) { return chunks; }

  return chunks.slice(0, maxChunks);
}

/**
 * Trim PM chat history to keep the most recent messages
 * within the budget's context char limit (30% allocated to history).
 */
function trimChatHistory(
  history: PmChatMessage[],
  budget: BridgeTokenBudget
): PmChatMessage[] {
  if (history.length === 0) { return []; }

  const MAX_MESSAGES = 20;
  const historyCharBudget = Math.floor(budget.maxContextChars * 0.15);
  let charCount = 0;
  const result: PmChatMessage[] = [];

  // Count-based window (max 20) with char budget as secondary limit
  const startIdx = Math.max(0, history.length - MAX_MESSAGES);
  for (let i = history.length - 1; i >= startIdx; i--) {
    const msg = history[i];
    const msgChars = msg.text.length + 20;
    if (charCount + msgChars > historyCharBudget) { break; }
    charCount += msgChars;
    result.unshift(msg);
  }

  return result;
}

/**
 * Truncate text to a maximum character count.
 * Appends "[truncated]" if content was cut.
 */
function trimToCharBudget(text: string, maxChars: number): string {
  if (text.length <= maxChars) { return text; }
  return text.slice(0, maxChars - 12) + " [truncated]";
}

