/**
 * Rough character count of an assembled PMRequestInput.
 * Used for logging and budget diagnostics, not billing.
 */
function estimateChars(input: PMRequestInput): number {
  let total = 0;
  total += input.objective.length;
  total += input.activeSynthesis.content.length;
  total += input.decisionsSummary.length;
  total += input.retrievalPack.reduce((sum, c) => sum + c.length, 0);
  total += input.pmChatHistory.reduce((sum, m) => sum + m.text.length, 0);
  total += input.userMessage.length;
  total += (input.bitacoraContext ?? "").length;
  total += (input.projectMemoryContext ?? "").length;
  return total;
}